const SUPABASE_URL = process.env.EXPO_PUBLIC_SUPABASE_URL!;
const SUPABASE_ANON_KEY = process.env.EXPO_PUBLIC_SUPABASE_ANON_KEY!;

export const supabase = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
  auth: {
    storage: {
      getItem: async (key: string) => AsyncStorage.getItem(key),
      setItem: async (key: string, value: string) => AsyncStorage.setItem(key, value),
      removeItem: async (key: string) => AsyncStorage.removeItem(key),
    },
    autoRefreshToken: true,
    persistSession: true,
    detectSessionInUrl: false,
    // PKCE: Expo SDK 54 + Hermes supports WebCrypto. Supabase projects created
    // after mid-2024 have implicit grant disabled by default, so we use PKCE.
    // The code verifier is generated by signInWithOAuth and stored in AsyncStorage,
    // then retrieved by exchangeCodeForSession after the browser redirect.
    flowType: "pkce",
  },
});

