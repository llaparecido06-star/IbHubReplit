const AuthContext = createContext<AuthContextType | null>(null);

// ── Persistent cache helpers ─────────────────────────────────────────────────
// Caching session + profile in AsyncStorage lets us pre-populate state before
// the Supabase getSession() round-trip completes, eliminating the cold-start
// spinner for users who are already logged in. The real session is validated
// in the background; if it changed (expired / sign-out on another device) the
// UI is updated after the fact.

const SESSION_CACHE_KEY = "@ibhub/auth_session_cache";
const PROFILE_CACHE_KEY = "@ibhub/profile_cache";

interface SessionCache {
  session: Session;
  userId: string;
}

async function readSessionCache(): Promise<SessionCache | null> {
  try {
    const raw = await AsyncStorage.getItem(SESSION_CACHE_KEY);
    if (!raw) return null;
    return JSON.parse(raw) as SessionCache;
  } catch {
    return null;
  }
}

async function writeSessionCache(session: Session): Promise<void> {
  try {
    await AsyncStorage.setItem(
      SESSION_CACHE_KEY,
      JSON.stringify({ session, userId: session.user.id } satisfies SessionCache),
    );
  } catch {}
}

async function readProfileCache(): Promise<Profile | null> {
  try {
    const raw = await AsyncStorage.getItem(PROFILE_CACHE_KEY);
    if (!raw) return null;
    return JSON.parse(raw) as Profile;
  } catch {
    return null;
  }
}

async function writeProfileCache(profile: Profile): Promise<void> {
  try {
    await AsyncStorage.setItem(PROFILE_CACHE_KEY, JSON.stringify(profile));
  } catch {}
}

async function clearAuthCache(): Promise<void> {
  try {
    await AsyncStorage.multiRemove([SESSION_CACHE_KEY, PROFILE_CACHE_KEY]);
  } catch {}
}

/** Parses `access_token`, `refresh_token`, and `type` from a deep link URL fragment */
function parseRecoveryUrl(url: string): { accessToken: string; refreshToken: string } | null {
  try {
    const fragment = url.split("#")[1] ?? url.split("?")[1] ?? "";
    const params = Object.fromEntries(new URLSearchParams(fragment));
    if (params.type === "recovery" && params.access_token && params.refresh_token) {
      return { accessToken: params.access_token, refreshToken: params.refresh_token };
    }
  } catch {}
  return null;
}

/**
 * A profile is "complete" if the user has chosen a username.
 * All registration paths (email/password and social-complete) require username,
 * so this is the most reliable signal. Checking areas_of_expertise would wrongly
 * flag users who registered before that field was added.
 */
function isProfileComplete(data: any): boolean {
  return !!data?.username?.trim();
}

export function AuthProvider({ children }: { children: React.ReactNode }) {
  const [session, setSession]                   = useState<Session | null>(null);
  const [user, setUser]                         = useState<User | null>(null);
  const [profile, setProfile]                   = useState<Profile | null>(null);
  const [loading, setLoading]                   = useState(true);
  const [isRecovering, setIsRecovering]         = useState(false);
  const [mustChangePassword, setMustChangePassword] = useState(false);
  const [needsProfileCompletion, setNeedsProfileCompletion] = useState(false);
  const [profileChecked, setProfileChecked]     = useState(false);
  const [activeCompany, setActiveCompany]       = useState<ActiveCompany | null>(null);

  // Guard against concurrent fetchProfile calls (common on Android where
  // onAuthStateChange fires SIGNED_IN + TOKEN_REFRESHED in quick succession).
  // Only one fetch runs at a time; subsequent calls for the same userId are
  // no-ops while the first is in flight.
  const fetchProfileInFlightRef = useRef<string | null>(null);

  const fetchProfile = useCallback(async (userId: string) => {
    // Guard: if a fetch for this user is already in flight, skip. This prevents
    // Android's rapid SIGNED_IN → TOKEN_REFRESHED sequence from running two
    // concurrent queries and creating a profileChecked race condition.
    if (fetchProfileInFlightRef.current === userId) {
      console.log(`[fetchProfile] skipping — already in flight for userId=${userId}`);
      return;
    }
    fetchProfileInFlightRef.current = userId;

    // Safety-net: if the Supabase query hangs (network lost mid-session, server
    // timeout, etc.) the finally block never runs and profileChecked stays false,
    // keeping the loading spinner up forever. This timer fires after 3 s and
    // unblocks the secondary loading guard in RootLayoutNav regardless.
    let timedOut = false;
    const tid = setTimeout(() => {
      timedOut = true;
      console.warn(`[fetchProfile] 3s timeout for userId=${userId} — unblocking profileChecked`);
      setProfileChecked(true);
      fetchProfileInFlightRef.current = null;
    }, 3_000);

    try {
      // Use limit(1) to avoid "multiple rows" error if duplicate profiles exist
      const { data: rows, error } = await supabase
        .from("profiles")
        .select("*")
        .or(`id.eq.${userId},user_id.eq.${userId}`)
        .limit(1);

      // If the timeout already fired, don't overwrite state with stale data.
      if (timedOut) return;

      const data = rows?.[0] ?? null;
      console.log(`[fetchProfile] userId=${userId} found=${!!data} error=${error?.message ?? null}`);
      if (error) {
        // Network failure, RLS denial, or server error — do NOT treat this as
        // "new user without profile". Keep whatever profile/needsCompletion state
        // is already set (could be from cache). Redirecting to social-complete
        // on a transient error would boot an existing user into the signup flow.
        console.warn(`[fetchProfile] Supabase error for userId=${userId}: ${error.message}. Keeping current profile state.`);
      } else if (data) {
        const d = data as any;
        const headline =
          d.headline ??
          ([d.position, d.company].filter(Boolean).join(" · ") || null);
        const areas_of_expertise: string[] =
          Array.isArray(d.areas_of_expertise) ? d.areas_of_expertise :
          Array.isArray(d.areas) ? d.areas : [];
        const profileData = { ...d, headline, areas_of_expertise } as Profile;
        setProfile(profileData);
        setNeedsProfileCompletion(!isProfileComplete(profileData));
        writeProfileCache(profileData);
        console.log(`[fetchProfile] profile loaded. username=${d.username ?? "null"} needsCompletion=${!isProfileComplete(profileData)}`);
      } else {
        // No error AND no data: profile row genuinely doesn't exist yet.
        // This is a new social-auth user who hasn't completed registration.
        console.warn(`[fetchProfile] No profile row found for userId=${userId}. Marking needsProfileCompletion=true`);
        setNeedsProfileCompletion(true);
      }
    } catch (e: any) {
      console.error(`[fetchProfile] Exception:`, e?.message);
    } finally {
      clearTimeout(tid);
      fetchProfileInFlightRef.current = null;
      // setProfileChecked is idempotent — safe to call even if the timeout
      // already fired it. React bails out of re-rendering when state is the
      // same value, so this causes no extra renders.
      setProfileChecked(true);
    }
  }, []);

  const refreshProfile = useCallback(async () => {
    if (user) await fetchProfile(user.id);
  }, [user, fetchProfile]);

  const refreshProfileByUserId = useCallback(async (userId: string) => {
    await fetchProfile(userId);
  }, [fetchProfile]);

  const patchProfile = useCallback((patch: Partial<Profile>) => {
    setProfile((prev) => prev ? { ...prev, ...patch } : prev);
  }, []);

  const clearProfileCompletion = useCallback(() => {
    setNeedsProfileCompletion(false);
  }, []);

  /** Handles a deep link URL — sets session if it is a password recovery link */
  const handleDeepLink = useCallback(async (url: string | null) => {
    if (!url) return;

    // ── Implicit flow: tokens in URL fragment (#access_token=...&type=recovery) ──
    const tokens = parseRecoveryUrl(url);
    if (tokens) {
      const { error } = await supabase.auth.setSession({
        access_token: tokens.accessToken,
        refresh_token: tokens.refreshToken,
      });
      if (!error) setIsRecovering(true);
      return;
    }

    // ── PKCE flow: one-time code in query string (?code=...) ──────────────────
    // Supabase projects with PKCE enabled send:
    //   - ibhub://reset-password?code=xxx  (password recovery)
    //   - ibhub://auth/callback?code=xxx   (OAuth sign-in — Android/iOS sometimes
    //     delivers this as a Linking event instead of returning it to
    //     openAuthSessionAsync, so we must handle it here too)
    const qs = url.split("?")[1] ?? "";
    const urlParams = Object.fromEntries(new URLSearchParams(qs));

    if (url.includes("reset-password") && urlParams.code) {
      try {
        const { error } = await supabase.auth.exchangeCodeForSession(urlParams.code);
        // PASSWORD_RECOVERY event fired by onAuthStateChange will set isRecovering=true.
        // Set it here too as a safety net in case the event arrives after this resolves.
        if (!error) setIsRecovering(true);
        else console.error("[handleDeepLink] reset-password PKCE exchange error:", error.message);
      } catch (e) {
        console.error("[handleDeepLink] reset-password PKCE exchange failed:", e);
      }
      return;
    }

    if ((url.includes("auth/callback") || url.includes("--/auth/callback")) && urlParams.code) {
      // OAuth callback delivered as a deep link (common on Android when Chrome Custom Tab
      // re-launches the app instead of returning through openAuthSessionAsync).
      // If openAuthSessionAsync ALSO captured the URL, this is a duplicate exchange —
      // the second call will fail silently with "code already used" which is harmless.
      try {
        console.log("[handleDeepLink] OAuth auth/callback received. Exchanging code...");
        const { error } = await supabase.auth.exchangeCodeForSession(urlParams.code);
        if (error) {
          // "code already used" is expected when openAuthSessionAsync already exchanged it
          if (!error.message.includes("already") && !error.message.includes("expired")) {
            console.error("[handleDeepLink] OAuth code exchange error:", error.message);
          }
        } else {
          console.log("[handleDeepLink] OAuth code exchanged. SIGNED_IN will fire.");
        }
      } catch (e) {
        console.error("[handleDeepLink] OAuth callback exchange failed:", e);
      }
      return;
    }

    // ── Referral deep link: ibhub://cadastro?ref=CODE or any URL with ?ref= ──
    try {
      const parsed = Linking.parse(url);
      const ref = parsed.queryParams?.ref;
      if (ref && typeof ref === "string" && ref.trim()) {
        await AsyncStorage.setItem("pending_invite_code", ref.trim().toUpperCase());
        console.log("[handleDeepLink] Referral code saved:", ref.trim().toUpperCase());
      }
    } catch (e) {
      console.warn("[handleDeepLink] Could not parse referral from URL:", e);
    }
  }, []);

  useEffect(() => {
    // maybeCompleteAuthSession is a no-op on native (web-only API), but it's
    // safe to call once at startup to ensure any in-flight web auth session
    // completes properly when running under expo-web.
    WebBrowser.maybeCompleteAuthSession();

    // 1. Resolve deep links BEFORE finalising loading state.
    //    If the app was cold-started by a password-recovery link (PKCE: ?code=xxx),
    //    we must exchange the code and set isRecovering=true BEFORE calling getSession()
    //    — otherwise getSession() returns null, loading becomes false, and RootLayoutNav
    //    redirects to /login while the exchange is still in flight (race condition).
    //
    // Safety net: if init hangs (network not ready at cold-start, token refresh
    // stalls, etc.) we must still unblock the UI so the user isn't stuck on the
    // loading spinner forever. The onAuthStateChange listener will eventually
    // fire INITIAL_SESSION / TOKEN_REFRESHED and set the session correctly.
    let loadingResolved = false;
    const resolveLoading = () => {
      if (!loadingResolved) {
        loadingResolved = true;
        setLoading(false);
      }
    };
    // Safety-net: if getSession() itself hangs (no network, token-refresh stall),
    // unblock the UI after 5s so the user isn't stuck on the spinner forever.
    // Also force profileChecked=true so the secondary loading guard doesn't
    // activate if session is already set when the timeout fires.
    const initTimeoutId = setTimeout(() => {
      console.warn("[AuthInit] 3s timeout reached — unblocking UI. Session will resolve via onAuthStateChange.");
      resolveLoading();
      setProfileChecked(true);
    }, 3_000);

    const init = async () => {
      try {
        // ── Deep link must be resolved first to avoid session-state races ──────
        const initialUrl = await Linking.getInitialURL();
        if (initialUrl) await handleDeepLink(initialUrl);

        // ── Cache-first: seed state from AsyncStorage before any network call ──
        // Reading both caches in parallel keeps this as fast as possible.
        const [cachedAuth, cachedProfile] = await Promise.all([
          readSessionCache(),
          readProfileCache(),
        ]);

        if (cachedAuth) {
          // Cache hit — show the app instantly, validate session in background.
          console.log(`[AuthInit] Cache hit for userId=${cachedAuth.userId}. Unblocking UI.`);
          setSession(cachedAuth.session);
          setUser(cachedAuth.session.user);
          setMustChangePassword(cachedAuth.session.user?.user_metadata?.must_change_password === true);

          if (cachedProfile) {
            setProfile(cachedProfile);
            setNeedsProfileCompletion(!isProfileComplete(cachedProfile));
            setProfileChecked(true);
          }

          clearTimeout(initTimeoutId);
          resolveLoading();

          // Background validation: confirm the session is still valid and
          // refresh profile data. This updates the UI without blocking it.
          const { data: { session: freshSession } } = await supabase.auth.getSession();
          if (freshSession) {
            setSession(freshSession);
            setUser(freshSession.user);
            setMustChangePassword(freshSession.user?.user_metadata?.must_change_password === true);
            writeSessionCache(freshSession);
            await fetchProfile(freshSession.user.id);
          } else {
            // Cached session was stale / refresh token expired → sign the user out.
            console.warn("[AuthInit] Cached session is no longer valid — clearing.");
            setSession(null);
            setUser(null);
            setProfile(null);
            setNeedsProfileCompletion(false);
            setProfileChecked(true);
            clearAuthCache();
          }
        } else {
          // No cache (first install, after explicit sign-out) → normal blocking flow.
          const { data: { session } } = await supabase.auth.getSession();
          setSession(session);
          setUser(session?.user ?? null);
          setMustChangePassword(session?.user?.user_metadata?.must_change_password === true);

          // ── Unblock the loading spinner as soon as we know the session state.
          // fetchProfile runs after this; profileChecked gates /(tabs) navigation
          // only when a session exists (avoids flash-to-tabs for social-auth users
          // who still need to complete their profile on /social-complete).
          clearTimeout(initTimeoutId);
          resolveLoading();

          if (session?.user) {
            writeSessionCache(session);
            await fetchProfile(session.user.id);
          } else {
            // No session → no profile to wait for. Unblock the secondary guard in
            // RootLayoutNav so a logged-out user never sees a second loading screen.
            setProfileChecked(true);
          }
        }
      } catch (e: any) {
        // Never let an unhandled error silently keep loading=true forever.
        // Clear the timeout (if it hadn't fired yet) and ensure both loading
        // and profileChecked are unblocked so the secondary guard in
        // RootLayoutNav never stays active indefinitely.
        console.error("[AuthInit] Unhandled error during init:", e?.message ?? e);
        clearTimeout(initTimeoutId);
        setProfileChecked(true);
      } finally {
        // resolveLoading is idempotent — safe to call again as a fallback in
        // case an exception was thrown before the explicit call above.
        resolveLoading();
      }
    };
    init();

    // 2. Auth state changes (including PASSWORD_RECOVERY and OAuth SIGNED_IN)
    const { data: { subscription } } = supabase.auth.onAuthStateChange(async (event, session) => {
      console.log(`[AuthState] event=${event} userId=${session?.user?.id ?? "null"}`);
      if (event === "PASSWORD_RECOVERY") {
        setIsRecovering(true);
      }
      // Always unblock the loading spinner on any auth event. Previously this
      // only fired when session was truthy, which meant INITIAL_SESSION with
      // session=null (unauthenticated first run) left loading=true until the
      // 5s safety-net timeout — causing a visible hang on every cold start
      // without a prior session. resolveLoading() is idempotent, so calling it
      // multiple times (here + in init()) is safe.
      resolveLoading();
      // If there is no session after any event, no profile will be fetched, so
      // profileChecked must be set here so the secondary guard in RootLayoutNav
      // (session && !profileChecked) is never permanently active.
      if (!session) {
        setProfileChecked(true);
      }
      setSession(session);
      setUser(session?.user ?? null);
      setMustChangePassword(session?.user?.user_metadata?.must_change_password === true);
      if (session?.user) {
        writeSessionCache(session);

        if (event === "SIGNED_IN") {
          Alert.alert('Debug 3/5', `SIGNED_IN recebido!\nuserId: ${session.user.id.slice(0, 8)}...\n\nBuscando perfil no banco de dados...`);
        }

        try {
          await fetchProfile(session.user.id);
        } catch (e: any) {
          Alert.alert('ERRO FATAL', `fetchProfile() lançou exceção:\n\n${e?.message ?? String(e)}`);
        }

        // Safety net: ensure a profile row exists for new social-auth users.
        // A Supabase DB trigger should create it, but this handles the case
        // where the trigger is missing or it created the row with null full_name.
        if (event === "SIGNED_IN") {
          try {
            const u = session.user;
            const meta = u.user_metadata ?? {};
            const googleName = (meta.full_name ?? meta.name ?? u.email?.split("@")[0] ?? "") as string;
            const googleAvatar = (meta.avatar_url ?? meta.picture ?? null) as string | null;

            // Fetch current profile state (limit 1 to handle any duplicate rows)
            const { data: rows } = await supabase
              .from("profiles")
              .select("id, full_name, avatar_url")
              .or(`id.eq.${u.id},user_id.eq.${u.id}`)
              .limit(1);
            const existing = rows?.[0] ?? null;
            console.log(`[SafetyNet] existing profile:`, existing ? `id=${existing.id}` : "null");

            if (!existing) {
              // No profile → create one with id = auth.uid() as primary key
              const { error: insertErr } = await supabase.from("profiles").insert({
                id: u.id,
                user_id: u.id,
                full_name: googleName || null,
                avatar_url: googleAvatar,
                plan: "gratuito",
              });
              console.log(`[SafetyNet] insert result:`, insertErr ? `ERROR: ${insertErr.message}` : "OK");
              if (insertErr) Alert.alert('ERRO FATAL', `Safety net insert falhou:\n\n${insertErr.message}`);
            } else if (!existing.full_name && googleName) {
              // Profile exists but has no name (trigger didn't set it) → fill it in
              const update: Record<string, string | null> = { user_id: u.id, full_name: googleName };
              if (!existing.avatar_url && googleAvatar) update.avatar_url = googleAvatar;
              const { error: updateErr } = await supabase.from("profiles").update(update).eq("id", existing.id);
              console.log(`[SafetyNet] update full_name result:`, updateErr ? `ERROR: ${updateErr.message}` : "OK");
              if (updateErr) Alert.alert('ERRO FATAL', `Safety net update falhou:\n\n${updateErr.message}`);
            } else {
              console.log(`[SafetyNet] Profile OK, no changes needed.`);
            }

            await fetchProfile(u.id);
            Alert.alert('Debug 4/5', `Perfil carregado com sucesso!\n\nAguardando RootLayoutNav chamar router.replace()...\n\nSe travar aqui: o problema está no useEffect de navegação em _layout.tsx.`);
          } catch (e: any) {
            console.error(`[SafetyNet] Exception:`, e?.message);
            Alert.alert('ERRO FATAL', `Exceção no bloco SIGNED_IN (safety net):\n\n${e?.message ?? String(e)}`);
          }
        }

        // Apply pending referral code (saved by registration screen before sign-up).
        if (event === "SIGNED_IN") {
          try {
            const pendingCode = await AsyncStorage.getItem("pending_invite_code");
            if (pendingCode) {
              const { data: prof } = await supabase
                .from("profiles")
                .select("invited_by_id")
                .eq("id", session.user.id)
                .single();
              if (!prof?.invited_by_id) {
                const { data: inviter } = await supabase
                  .from("profiles")
                  .select("id")
                  .eq("referral_code", pendingCode.trim().toUpperCase())
                  .maybeSingle();
                if (inviter?.id && inviter.id !== session.user.id) {
                  await supabase
                    .from("profiles")
                    .update({ invited_by_id: inviter.id })
                    .eq("id", session.user.id);
                }
              }
              await AsyncStorage.removeItem("pending_invite_code");
            }
          } catch {}
        }
      } else {
        setProfile(null);
        setNeedsProfileCompletion(false);
        // Do NOT reset profileChecked to false here. When session?.user is null,
        // the !session branch above (line ~481) already set profileChecked=true.
        // Resetting it here creates a race: _layout.tsx sees session && !profileChecked
        // (during Android's SIGNED_IN → TOKEN_REFRESHED burst) and hangs on the
        // spinner indefinitely, causing the infinite login loop.
        clearAuthCache();
        fetchProfileInFlightRef.current = null;
      }
    });

    // 3. Handle deep links while app is already open (warm start).
    //    Cold-start is handled inside init() above to avoid race conditions.
    const linkSub = Linking.addEventListener("url", ({ url }) => handleDeepLink(url));

    return () => {
      subscription.unsubscribe();
      linkSub.remove();
    };
  }, [fetchProfile, handleDeepLink]);

  // ── Realtime: re-fetch profile on Stripe/plan changes; force sign-out if banned ──
  useEffect(() => {
    if (!user?.id) return;

    const channelId = `profile_stripe_${user.id}_${Math.random().toString(36).slice(2)}`;
    const channel = supabase
      .channel(channelId)
      .on(
        "postgres_changes",
        {
          event: "UPDATE",
          schema: "public",
          table: "profiles",
          filter: `id=eq.${user.id}`,
        },
        async (payload) => {
          const updated = payload.new as { is_banned?: boolean };
          if (updated.is_banned === true) {
            // Store flag so login screen can display the suspension message
            await AsyncStorage.setItem("account_suspended", "true");
            await supabase.auth.signOut();
            return;
          }
          fetchProfile(user.id).catch(() => {});
        },
      )
      .subscribe();

    return () => {
      supabase.removeChannel(channel);
    };
  }, [user?.id, fetchProfile]);

  const clearRecovery = useCallback(() => setIsRecovering(false), []);

  const signIn = async (email: string, password: string) => {
    try {
      console.log("[signIn] step 1 — calling signInWithPassword");
      const { error } = await supabase.auth.signInWithPassword({ email, password });
      if (error) {
        const msg = error.message ?? "";
        console.error("[signIn] signInWithPassword error:", msg);
        Alert.alert('ERRO FATAL', `signInWithPassword falhou:\n\n${msg}`);
        if (msg.toLowerCase().includes("ban") || msg.toLowerCase().includes("suspend")) {
          return { error: "Sua conta foi suspensa. Entre em contato com o suporte." };
        }
        return { error: msg };
      }

      console.log("[signIn] step 2 — signInWithPassword OK, calling getUser");
      const { data: { user: authedUser }, error: getUserErr } = await supabase.auth.getUser();
      if (getUserErr) {
        console.error("[signIn] getUser error:", getUserErr.message);
        Alert.alert('ERRO FATAL', `getUser() falhou após signIn:\n\n${getUserErr.message}`);
        return { error: getUserErr.message };
      }
      console.log("[signIn] step 3 — getUser returned userId:", authedUser?.id ?? "null");

      if (authedUser) {
        console.log("[signIn] step 4 — checking is_banned for userId:", authedUser.id);
        const { data: prof, error: banErr } = await supabase
          .from("profiles")
          .select("is_banned")
          .eq("id", authedUser.id)
          .maybeSingle();
        if (banErr) {
          console.error("[signIn] is_banned query error:", banErr.message);
          Alert.alert('ERRO FATAL', `Consulta is_banned falhou:\n\n${banErr.message}`);
          return { error: banErr.message };
        }
        console.log("[signIn] step 5 — is_banned:", (prof as { is_banned?: boolean } | null)?.is_banned ?? false);
        if ((prof as { is_banned?: boolean } | null)?.is_banned) {
          await supabase.auth.signOut();
          return { error: "Sua conta foi suspensa. Entre em contato com o suporte." };
        }
      }

      console.log("[signIn] step 6 — returning OK, waiting for onAuthStateChange to drive navigation");
      return { error: null };
    } catch (e: any) {
      const msg = e?.message ?? String(e);
      console.error("[signIn] unhandled exception:", msg);
      Alert.alert('ERRO FATAL', `Exceção não tratada em signIn():\n\n${msg}`);
      return { error: msg };
    }
  };

  const signUp = async (email: string, password: string, fullName: string) => {
    const { data, error } = await supabase.auth.signUp({
      email,
      password,
      options: { data: { full_name: fullName } },
    });
    if (error) return { error: error.message };

    if (data.user) {
      const { error: signInError } = await supabase.auth.signInWithPassword({ email, password });
      if (signInError) {
        return { error: "Conta criada! Verifique seu e-mail para confirmar o cadastro antes de entrar." };
      }
    }
    return { error: null };
  };

  /**
   * Build the redirect URI for OAuth.
   *
   * - Expo Go (dev): Linking.createURL returns exp://[host]/--/auth/callback
   * - Production / dev build: returns ibhub://auth/callback
   * Both must be allowlisted in the Supabase Redirect URLs config.
   *
   * Note on Android: Chrome Custom Tab fires an Android intent for custom-scheme
   * URLs (exp://, ibhub://) which cold-starts the app ("Fecha e Abre" in Expo Go).
   * This is a known Expo Go limitation — in a production build with the correct
   * Android launchMode the experience is seamless. The race approach below clears
   * the loading spinner while handleDeepLink finishes the PKCE exchange.
   */
  const getRedirectUri = (): string => Linking.createURL("auth/callback");

  /**
   * Parse the OAuth redirect URL returned by openAuthSessionAsync.
   * Implicit flow:  tokens are in the URL *fragment* (#access_token=…)
   * PKCE flow:      code is in the *query string* (?code=…)
   * Returns whichever is found first.
   */
  const parseOAuthRedirect = (url: string) => {
    const parseKV = (str: string) => {
      const out: Record<string, string> = {};
      (str || "").split("&").forEach(pair => {
        const eq = pair.indexOf("=");
        if (eq < 1) return;
        try {
          out[decodeURIComponent(pair.slice(0, eq))] = decodeURIComponent(pair.slice(eq + 1));
        } catch {}
      });
      return out;
    };

    // Fragment comes after #; query comes after ? but before #
    const hashIdx   = url.indexOf("#");
    const queryIdx  = url.indexOf("?");
    const fragment  = hashIdx  >= 0 ? url.slice(hashIdx  + 1) : "";
    const query     = queryIdx >= 0 ? url.slice(queryIdx + 1, hashIdx >= 0 ? hashIdx : undefined) : "";

    const frag = parseKV(fragment);
    if (frag.access_token && frag.refresh_token) {
      return { type: "tokens" as const, accessToken: frag.access_token, refreshToken: frag.refresh_token };
    }

    const q = parseKV(query);
    if (q.access_token && q.refresh_token) {
      return { type: "tokens" as const, accessToken: q.access_token, refreshToken: q.refresh_token };
    }
    if (q.code) {
      return { type: "code" as const, code: q.code };
    }

    return null;
  };

  const signInWithOAuthProvider = async (
    provider: "google" | "apple"
  ): Promise<{ error: string | null }> => {
    try {
      const redirectTo = getRedirectUri();
      console.log(`[OAuth] Starting ${provider} login. redirectTo:`, redirectTo);

      const { data, error } = await supabase.auth.signInWithOAuth({
        provider,
        options: { redirectTo, skipBrowserRedirect: true },
      });
      if (error) {
        console.error(`[OAuth] signInWithOAuth error:`, error.message);
        return { error: error.message };
      }
      if (!data?.url) return { error: `Não foi possível iniciar o login com ${provider}.` };

      console.log(`[OAuth] Opening browser for ${provider}...`);

      if (Platform.OS === "android") {
        // ── Android (Google AND Apple) ───────────────────────────────────────
        // On Android, Chrome Custom Tab fires the OAuth redirect as an Android
        // intent (custom scheme: ibhub://auth/callback?code=xxx). This intent is
        // delivered via Linking to handleDeepLink, which calls
        // exchangeCodeForSession and stores the session. The SIGNED_IN event then
        // fires in the main onAuthStateChange subscription in AuthProvider, which
        // sets session state and navigates to /(tabs).
        //
        // IMPORTANT: openAuthSessionAsync on Android does NOT reliably resolve
        // when the Chrome Custom Tab is dismissed via a custom-scheme redirect
        // (the .then() callback may never fire). Waiting for it — even with a
        // short inner timeout — leaves the login button spinner running for up to
        // 60 s while the session is already saved and navigation already happened
        // in the main subscription. The user sees "eternal loading."
        //
        // Fix: fire the browser and return immediately. The loading indicator on
        // the button shows only during the brief signInWithOAuth URL fetch (~500 ms).
        // Navigation to /(tabs) happens automatically via RootLayoutNav when
        // SIGNED_IN fires in the main onAuthStateChange handler.
        WebBrowser.openAuthSessionAsync(data.url, redirectTo).catch((e) => {
          console.warn(`[OAuth] Android (${provider}): openAuthSessionAsync error:`, e);
        });
        console.log(`[OAuth] Android (${provider}): browser opened, returning immediately.`);
        return { error: null };
      }

      // ── iOS (and fallback) ────────────────────────────────────────────────
      // ASWebAuthenticationSession on iOS CAN intercept the redirect URL before
      // the system navigates to it, so openAuthSessionAsync returns "success".
      const result = await WebBrowser.openAuthSessionAsync(data.url, redirectTo);
      console.log(`[OAuth] Browser result type:`, result.type);

      if (result.type === "cancel") return { error: null };
      if (result.type === "dismiss") {
        console.warn("[OAuth] Browser dismissed without completing auth.");
        return { error: null };
      }

      if (result.type === "success" && result.url) {
        const safeUrl = result.url.replace(/access_token=[^&]+/, "access_token=REDACTED").replace(/refresh_token=[^&]+/, "refresh_token=REDACTED");
        console.log(`[OAuth] Redirect URL received:`, safeUrl);

        const parsed = parseOAuthRedirect(result.url);
        console.log(`[OAuth] Parsed type:`, parsed?.type ?? "null");

        if (parsed?.type === "tokens") {
          const { error: err } = await supabase.auth.setSession({
            access_token: parsed.accessToken,
            refresh_token: parsed.refreshToken,
          });
          if (err) {
            console.error("[OAuth] setSession error:", err.message);
            return { error: err.message };
          }
          console.log("[OAuth] Session set via implicit tokens.");
        } else if (parsed?.type === "code") {
          console.log("[OAuth] Exchanging PKCE code for session...");
          const { error: err } = await supabase.auth.exchangeCodeForSession(parsed.code);
          if (err) {
            console.error("[OAuth] exchangeCodeForSession error:", err.message);
            return { error: err.message };
          }
          console.log("[OAuth] PKCE exchange success.");
        } else {
          console.warn("[OAuth] Could not parse tokens or code from redirect URL:", safeUrl);
          return { error: "Não foi possível completar o login. Verifique as configurações de redirecionamento." };
        }
      }
      return { error: null };
    } catch (e: any) {
      console.error(`[OAuth] Unexpected error:`, e?.message);
      return { error: e?.message ?? `Erro ao entrar com ${provider}.` };
    }
  };

  const signInWithGoogle = () => signInWithOAuthProvider("google");

  const signInWithApple = async (): Promise<{ error: string | null }> => {
    // iOS: native Sign In with Apple → Supabase signInWithIdToken (no browser needed)
    if (Platform.OS === "ios") {
      try {
        const rawNonce = Math.random().toString(36).substring(2)
          + Math.random().toString(36).substring(2);
        const msgBuffer = new TextEncoder().encode(rawNonce);
        const hashBuffer = await crypto.subtle.digest("SHA-256", msgBuffer);
        const hashedNonce = Array.from(new Uint8Array(hashBuffer))
          .map(b => b.toString(16).padStart(2, "0"))
          .join("");

        const credential = await AppleAuthentication.signInAsync({
          requestedScopes: [
            AppleAuthentication.AppleAuthenticationScope.FULL_NAME,
            AppleAuthentication.AppleAuthenticationScope.EMAIL,
          ],
          nonce: hashedNonce,
        });

        if (!credential.identityToken) {
          return { error: "Apple não retornou um token de identificação." };
        }

        const { error } = await supabase.auth.signInWithIdToken({
          provider: "apple",
          token: credential.identityToken,
          nonce: rawNonce,
        });

        if (error) {
          console.error("[Apple] signInWithIdToken error:", error.message);
          return { error: error.message };
        }
        return { error: null };
      } catch (e: any) {
        if (e.code === "ERR_REQUEST_CANCELED") return { error: null }; // user cancelled
        console.error("[Apple] native sign-in error:", e);
        return { error: e?.message ?? "Erro ao fazer login com Apple." };
      }
    }

    // Android / Web: fallback to web OAuth flow.
    // signInWithOAuthProvider's Android branch is provider-agnostic and applies
    // the same hardened SIGNED_IN-vs-browser-close race handling that was added
    // for Google. Apple-on-Android automatically inherits that fix here — do
    // not duplicate or reimplement that logic in this function.
    return signInWithOAuthProvider("apple");
  };

  const signOut = async () => {
    setActiveCompany(null);
    setNeedsProfileCompletion(false);
    setProfileChecked(false);
    clearAuthCache();
    await supabase.auth.signOut();
  };

  const resetPassword = async (email: string) => {
    // Use Linking.createURL so the scheme adapts correctly across environments:
    // - Development (Expo Go): exp://.../@/reset-password
    // - Production native build: ibhub://reset-password
    const { error } = await supabase.auth.resetPasswordForEmail(email, {
      redirectTo: Linking.createURL("reset-password"),
    });
    return { error: error?.message ?? null };
  };

  const updatePassword = async (newPassword: string) => {
    const { error } = await supabase.auth.updateUser({ password: newPassword });
    if (!error) {
      setIsRecovering(false);
      setMustChangePassword(false);
      // Clear the flag in user metadata so it doesn't persist across sessions
      await supabase.auth.updateUser({ data: { must_change_password: false } }).catch(() => {});
    }
    return { error: error?.message ?? null };
  };

  return (
    <AuthContext.Provider
      value={{
        session, user, profile, loading, isRecovering, mustChangePassword, needsProfileCompletion,
        profileChecked,
        activeCompany, setActiveCompany,
        signIn, signUp, signInWithGoogle, signInWithApple, signOut,
        resetPassword, updatePassword, clearRecovery, clearProfileCompletion,
        refreshProfile, refreshProfileByUserId, patchProfile,
      }}
    >
      {children}
    </AuthContext.Provider>
  );
}

export function useAuth() {
  const ctx = useContext(AuthContext);
  if (!ctx) throw new Error("useAuth must be used inside AuthProvider");
  return ctx;
}
