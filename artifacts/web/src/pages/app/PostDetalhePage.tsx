/** Returns true if the content was generated by the canonical wine-tasting form
 *  (matches the WINE_FIELDS prefixes used by parseWineContent). */
function looksLikeWine(content: string): boolean {
  return /^🍷 Degustação:/m.test(content) || (/^⭐/.test(content) && /Pontuação/.test(content));
}

/** Stable serialisation of poll fields that affect display, to compare two
 *  poll snapshots and ignore unrelated row updates. */
function pollContentKey(p: Poll | null | undefined): string {
  if (!p) return "";
  return JSON.stringify([p.options, p.total_votes, p.closed, p.expires_at, p.allow_multiple, p.user_votes]);
}

const GOLD = "#c9a84c";
const NAVY = "#0d1b2a";
const BG = "#f5f5f0";
const BORDER = "#e8e8e3";
const MUTED = "#7a8494";


function Avatar({ url, name, size = 40 }: { url?: string | null; name?: string | null; size?: number }) {
  return (
    <div style={{ width: size, height: size, borderRadius: "50%", overflow: "hidden", backgroundColor: BORDER, flexShrink: 0, display: "flex", alignItems: "center", justifyContent: "center" }}>
      {url ? <img src={url} alt="" style={{ width: "100%", height: "100%", objectFit: "cover" }} /> : <span style={{ fontSize: size * 0.45 }}>🍷</span>}
    </div>
  );
}

type MentionMap = Record<string, { id: string; isCompany: boolean }>;

function renderMentionText(
  text: string,
  mentionMap: MentionMap,
  navigate: (path: string) => void,
): React.ReactNode {
  const TOKEN_RE = /(@[\w.]+|https?:\/\/[^\s<>"']+[^\s<>"'.,;:!?)])/g;
  const parts = text.split(TOKEN_RE);
  return parts.map((part, i) => {
    if (/^@[\w.]+$/.test(part)) {
      const entry = mentionMap[part.slice(1).toLowerCase()];
      if (entry) {
        const path = entry.isCompany ? `/app/empresa/${entry.id}` : `/app/usuario/${entry.id}`;
        return (
          <span key={i} onClick={e => { e.stopPropagation(); navigate(path); }} style={{ color: GOLD, fontWeight: 700, cursor: "pointer" }}>
            {part}
          </span>
        );
      }
    }
    if (/^https?:\/\//.test(part)) {
      return (
        <a key={i} href={part} target="_blank" rel="noopener noreferrer" style={{ color: GOLD, textDecoration: "underline", wordBreak: "break-all" }} onClick={e => e.stopPropagation()}>
          {part}
        </a>
      );
    }
    return <React.Fragment key={i}>{part}</React.Fragment>;
  });
}

async function buildMentionMap(texts: string[]): Promise<MentionMap> {
  const handles = [...new Set((texts.join(" ").match(/@([\w.]+)/g) ?? []).map(m => m.slice(1).toLowerCase()))];
  if (!handles.length) return {};
  const [{ data: profiles }, { data: companies }] = await Promise.all([
    supabase.from("profiles").select("id, username").in("username", handles),
    supabase.from("company_pages").select("id, slug").in("slug", handles),
  ]);
  const map: MentionMap = {};
  for (const p of (profiles ?? [])) if ((p as any).username) map[(p as any).username.toLowerCase()] = { id: (p as any).id, isCompany: false };
  for (const c of (companies ?? [])) if ((c as any).slug) map[(c as any).slug.toLowerCase()] = { id: (c as any).id, isCompany: true };
  return map;
}

function CommentItem({ comment, depth = 0, onReply, currentUserId, mentionMap, highlighted = false, highlightRef }: {
  comment: AppComment;
  depth?: number;
  onReply: (id: string, name: string) => void;
  currentUserId?: string;
  mentionMap: MentionMap;
  highlighted?: boolean;
  highlightRef?: React.RefObject<HTMLDivElement | null>;
}) {
  const [, setLocation] = useLocation();
  const [liked, setLiked] = useState(!!comment.is_liked);
  const [likesCount, setLikesCount] = useState(comment.likes_count ?? 0);
  const [toggling, setToggling] = useState(false);
  const [flash, setFlash] = useState(highlighted);

  useEffect(() => {
    if (!highlighted) return;
    const timer = setTimeout(() => setFlash(false), 2000);
    return () => clearTimeout(timer);
  }, [highlighted]);

  const goToAuthor = () => {
    if (!comment.author?.id) return;
    comment.author.id === currentUserId ? setLocation("/app/perfil") : setLocation(`/app/usuario/${comment.author.id}`);
  };

  const handleLike = async () => {
    if (!currentUserId || toggling) return;
    setToggling(true);
    const newLiked = !liked;
    setLiked(newLiked);
    setLikesCount(c => newLiked ? c + 1 : Math.max(0, c - 1));
    await toggleCommentLike(comment.id, currentUserId, liked);
    setToggling(false);
  };

  return (
    <div ref={highlighted ? highlightRef : undefined} style={{ marginLeft: depth * 24, marginBottom: 10 }}>
      <div style={{ display: "flex", gap: 10, alignItems: "flex-start" }}>
        <div onClick={goToAuthor} style={{ cursor: comment.author?.id ? "pointer" : "default", flexShrink: 0 }}>
          <Avatar url={comment.author?.avatar_url} name={comment.author?.full_name} size={34} />
        </div>
        <div style={{
          flex: 1,
          backgroundColor: depth === 0 ? BG : "#fff",
          borderRadius: 10,
          padding: "10px 14px",
          border: flash ? `2px solid ${GOLD}` : `1px solid ${BORDER}`,
          transition: "border-color 0.4s",
        }}>
          <div onClick={goToAuthor} style={{ fontWeight: 700, fontSize: 13, color: NAVY, marginBottom: 4, cursor: comment.author?.id ? "pointer" : "default", display: "inline-block" }}>
            {comment.author?.full_name ?? "Usuário"}
          </div>
          <div style={{ fontSize: 14, color: NAVY, lineHeight: 1.5, whiteSpace: "pre-wrap", wordBreak: "break-word" }}>
            {renderMentionText(comment.content, mentionMap, setLocation)}
          </div>
          <div style={{ display: "flex", gap: 16, marginTop: 8, alignItems: "center" }}>
            <span style={{ fontSize: 11, color: MUTED }}>{relativeDate(comment.created_at)}</span>
            <button
              onClick={() => onReply(comment.id, comment.author?.full_name ?? "Usuário")}
              style={{ fontSize: 11, color: GOLD, fontWeight: 700, background: "none", border: "none", cursor: "pointer", padding: 0 }}
            >
              Responder
            </button>
            <button
              onClick={handleLike}
              disabled={!currentUserId}
              style={{ display: "flex", alignItems: "center", gap: 3, fontSize: 11, color: liked ? "#e53e3e" : MUTED, fontWeight: liked ? 700 : 500, background: "none", border: "none", cursor: currentUserId ? "pointer" : "default", padding: 0, transition: "color 0.15s" }}
            >
              {liked ? "❤️" : "🤍"} {likesCount > 0 ? likesCount : ""}
            </button>
          </div>
        </div>
      </div>
      {(comment.replies ?? []).map(r => (
        <CommentItem key={r.id} comment={r} depth={depth + 1} onReply={onReply} currentUserId={currentUserId} mentionMap={mentionMap} />
      ))}
    </div>
  );
}

export default function PostDetalhePage() {
  const [, params] = useRoute("/app/posts/:id");
  const [, setLocation] = useLocation();
  const search = useSearch();
  const { profile, activeCompany } = useAuth();
  const postId = params?.id;
  const companyId = activeCompany?.id ?? null;
  const highlightCommentId = new URLSearchParams(search).get("commentId") ?? undefined;
  const highlightRef = useRef<HTMLDivElement | null>(null);

  const [post, setPost] = useState<Post | null>(null);
  const [comments, setComments] = useState<AppComment[]>([]);
  const [mentionMap, setMentionMap] = useState<MentionMap>({});
  const [loading, setLoading] = useState(true);
  const [commentText, setCommentText] = useState("");
  const [replyTo, setReplyTo] = useState<{ id: string; name: string } | null>(null);
  const [submitting, setSubmitting] = useState(false);

  const load = useCallback(async () => {
    if (!postId) return;
    setLoading(true);
    const [p, c] = await Promise.all([
      fetchPostById(postId, profile?.id, companyId),
      fetchPostComments(postId, profile?.id),
    ]);
    setPost(p);
    setComments(c);
    setLoading(false);
  }, [postId, profile?.id, companyId]);

  useEffect(() => { load(); }, [load]);

  useEffect(() => {
    const texts = comments.flatMap(c => [c.content, ...(c.replies ?? []).map(r => r.content)]);
    buildMentionMap(texts).then(setMentionMap);
  }, [comments]);

  // Scroll to highlighted comment after comments load
  useEffect(() => {
    if (!highlightCommentId || !comments.length || loading) return;
    const timer = setTimeout(() => {
      highlightRef.current?.scrollIntoView({ behavior: "smooth", block: "center" });
    }, 300);
    return () => clearTimeout(timer);
  }, [highlightCommentId, comments.length, loading]);

  useEffect(() => {
    if (!postId || !profile?.id) return;
    const ch = supabase
      .channel(`post_comments_${postId}`)
      .on("postgres_changes", {
        event: "INSERT",
        schema: "public",
        table: "comments",
        filter: `post_id=eq.${postId}`,
      }, async (payload) => {
        const raw = payload.new as any;
        if (raw.user_id === profile.id) return;
        const { data: authorData } = await supabase
          .from("profiles")
          .select("id, full_name, avatar_url, headline, plan")
          .eq("id", raw.user_id)
          .single();
        const newComment: AppComment = {
          id: raw.id,
          post_id: raw.post_id,
          user_id: raw.user_id,
          content: raw.content,
          created_at: raw.created_at,
          parent_comment_id: raw.parent_comment_id ?? null,
          is_liked: false,
          likes_count: 0,
          replies: [],
          author: authorData ?? undefined,
        };
        setComments(prev => {
          if (raw.parent_comment_id) {
            return prev.map(cm =>
              cm.id === raw.parent_comment_id
                ? { ...cm, replies: [...(cm.replies ?? []), newComment] }
                : cm
            );
          }
          if (prev.some(c => c.id === raw.id)) return prev;
          return [...prev, newComment];
        });
        setPost(prev => prev ? { ...prev, comments_count: prev.comments_count + 1 } : prev);
      })
      .subscribe();
    return () => { supabase.removeChannel(ch); };
  }, [postId, profile?.id]);

  // Realtime: subscribe to UPDATE on this post and patch only the poll field.
  useEffect(() => {
    if (!postId) return;
    const userId = profile?.id;
    const uid = Math.random().toString(36).slice(2, 8);
    const ch = supabase
      .channel(`post_poll_${postId}_${uid}`)
      .on("postgres_changes", {
        event: "UPDATE",
        schema: "public",
        table: "posts",
        filter: `id=eq.${postId}`,
      }, (payload) => {
        const next = payload.new as { poll?: Poll | null };
        const nextPoll = next?.poll;
        if (!nextPoll) return;
        setPost(prev => {
          if (!prev) return prev;
          // Skip if poll content unchanged (e.g. UPDATE was for likes_count).
          if (pollContentKey(prev.poll) === pollContentKey(nextPoll)) return prev;
          const indices = userId ? normalizePollIndices(nextPoll.user_votes, userId) : [];
          return {
            ...prev,
            poll: { ...nextPoll, user_voted_indices: indices, user_voted_index: indices[0] ?? null },
          };
        });
      })
      .subscribe();
    return () => { supabase.removeChannel(ch); };
  }, [postId, profile?.id]);


  const handleBookmark = async () => {
    if (!post || !profile?.id) return;
    await toggleBookmarkPost(post.id, profile.id, !!post.is_bookmarked);
    setPost(prev => prev ? { ...prev, is_bookmarked: !prev.is_bookmarked } : prev);
  };

  const handleComment = async () => {
    if (!post || !profile?.id || !commentText.trim()) return;
    setSubmitting(true);
    const c = await addPostComment(post.id, profile.id, commentText.trim(), replyTo?.id, profile.full_name ?? undefined);
    if (c) {
      setComments(prev => replyTo
        ? prev.map(cm => cm.id === replyTo.id ? { ...cm, replies: [...(cm.replies ?? []), c] } : cm)
        : [...prev, c]
      );
      setPost(prev => prev ? { ...prev, comments_count: prev.comments_count + 1 } : prev);
      const saved_text = commentText.trim();
      setCommentText("");
      setReplyTo(null);
      if (saved_text.includes("@") && profile?.id) {
        const actorName = profile.full_name ?? "Usuário";
        sendMentionNotifications(saved_text, profile.id, actorName, post.id, c.id);
      }
    }
    setSubmitting(false);
  };

  const handleReply = (id: string, name: string) => {
    setReplyTo({ id, name });
  };

  const handleReact = async (reaction: ReactionType = "saude") => {
    if (!post || !profile?.id) return;
    const wasLiked = !!post.is_liked;
    const isSameReaction = wasLiked && post.reaction_type === reaction;
    if (isSameReaction) {
      setPost(prev => prev ? { ...prev, is_liked: false, reaction_type: null, likes_count: Math.max(0, prev.likes_count - 1) } : prev);
      await toggleLikePost(post.id, profile.id, true, reaction, companyId, profile.full_name ?? undefined);
    } else if (wasLiked) {
      setPost(prev => prev ? { ...prev, reaction_type: reaction } : prev);
      await changeReactionPost(post.id, profile.id, reaction, companyId);
    } else {
      setPost(prev => prev ? { ...prev, is_liked: true, reaction_type: reaction, likes_count: prev.likes_count + 1 } : prev);
      await toggleLikePost(post.id, profile.id, false, reaction, companyId, profile.full_name ?? undefined);
    }
  };

  const handleFocusComment = () => {
    document.querySelector<HTMLTextAreaElement>(".mention-textarea")?.scrollIntoView({ behavior: "smooth", block: "center" });
  };

  if (loading) {
    return (
      <AppShell>
        <div style={{ maxWidth: 720, margin: "0 auto", padding: 32, textAlign: "center", color: MUTED }}>Carregando publicação...</div>
      </AppShell>
    );
  }

  if (!post) {
    return (
      <AppShell>
        <div style={{ maxWidth: 720, margin: "0 auto", padding: 32, textAlign: "center" }}>
          <div style={{ fontSize: 48, marginBottom: 12 }}>😕</div>
          <p style={{ color: MUTED }}>Publicação não encontrada.</p>
          <button onClick={() => setLocation("/app")} style={{ marginTop: 16, padding: "8px 20px", backgroundColor: GOLD, color: "#fff", border: "none", borderRadius: 8, cursor: "pointer", fontWeight: 700 }}>Voltar ao feed</button>
        </div>
      </AppShell>
    );
  }

  return (
    <AppShell>
      <div style={{ maxWidth: 720, margin: "0 auto", padding: "24px 16px" }}>
        <button onClick={() => setLocation("/app")} style={{ display: "flex", alignItems: "center", gap: 6, color: GOLD, fontWeight: 700, background: "none", border: "none", cursor: "pointer", marginBottom: 20, fontSize: 14 }}>
          ← Voltar ao feed
        </button>

        <div style={{ backgroundColor: "#fff", borderRadius: 14, border: `1px solid ${BORDER}`, overflow: "hidden", marginBottom: 20 }}>
          <div style={{ padding: 20 }}>
            <div style={{ display: "flex", alignItems: "center", gap: 12, marginBottom: 16 }}>
              <Avatar url={post.author?.avatar_url} name={post.author?.full_name} size={46} />
              <div>
                <div
                  onClick={() => post.author && setLocation(`/app/usuario/${post.author.id}`)}
                  style={{ fontWeight: 700, color: NAVY, fontSize: 15, cursor: "pointer" }}
                >
                  {post.author?.full_name ?? "Usuário"}
                </div>
                {post.author?.headline && <div style={{ color: MUTED, fontSize: 12 }}>{post.author.headline}</div>}
                <div style={{ color: MUTED, fontSize: 11, marginTop: 2 }}>
                  {relativeDate(post.created_at)}
                </div>
              </div>
            </div>

            {looksLikeWine(post.content) ? (
              <div style={{ marginBottom: 16 }}>
                <WineTastingCardWeb content={post.content} />
              </div>
            ) : (
              <p style={{ fontSize: 16, color: NAVY, lineHeight: 1.65, marginBottom: 16, whiteSpace: "pre-wrap" }}>{post.content}</p>
            )}

            {post.poll && profile?.id && (
              <div style={{ margin: "0 -20px 16px" }}>
                <PollDisplay
                  poll={post.poll}
                  postId={post.id}
                  currentUserId={profile.id}
                  onVote={(_pid, updatedPoll) => setPost(prev => prev ? { ...prev, poll: updatedPoll } : prev)}
                />
              </div>
            )}

            {post.image_url && (
              <img src={post.image_url} alt="" style={{ width: "100%", height: "auto", maxHeight: 640, objectFit: "contain", display: "block", backgroundColor: "#f2f3f5", borderRadius: 10, marginBottom: 12 }} />
            )}
            {post.image_urls && post.image_urls.length > 0 && !post.image_url && (
              post.image_urls.length === 1 ? (
                <img src={post.image_urls[0]} alt="" style={{ width: "100%", height: "auto", maxHeight: 640, objectFit: "contain", display: "block", backgroundColor: "#f2f3f5", borderRadius: 10, marginBottom: 12 }} />
              ) : (
                <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 4, marginBottom: 12 }}>
                  {post.image_urls.slice(0, 4).map((url, i) => (
                    <img key={i} src={url} alt="" style={{ width: "100%", height: 220, objectFit: "cover", borderRadius: 8 }} />
                  ))}
                </div>
              )
            )}
          </div>

          {/* Video — full card width, outside padding */}
          {post.video_url && (
            <VideoPlayer src={post.video_url} />
          )}

          {/* Action bar — shared with feed via PostActionsBar so look + behavior stay identical */}
          <PostActionsBar
            post={post}
            onReact={handleReact}
            onComment={handleFocusComment}
            onBookmark={handleBookmark}
          />
        </div>

        <div style={{ backgroundColor: "#fff", borderRadius: 14, border: `1px solid ${BORDER}`, padding: 20, marginBottom: 20 }}>
          <h3 style={{ fontSize: 16, fontWeight: 700, color: NAVY, marginBottom: 16 }}>
            Comentários ({post.comments_count})
          </h3>

          {profile && (
            <div style={{ marginBottom: 16 }}>
              {replyTo && (
                <div style={{ fontSize: 12, color: MUTED, marginBottom: 6, display: "flex", alignItems: "center", gap: 8 }}>
                  ↩️ Respondendo a <strong>{replyTo.name}</strong>
                  <button onClick={() => setReplyTo(null)} style={{ background: "none", border: "none", cursor: "pointer", color: MUTED, fontSize: 16, lineHeight: 1 }}>×</button>
                </div>
              )}
              <div style={{ display: "flex", gap: 10, alignItems: "flex-start" }}>
                <Avatar url={profile.avatar_url} name={profile.full_name} size={36} />
                <div style={{ flex: 1 }}>
                  <MentionTextArea
                    value={commentText}
                    onChange={setCommentText}
                    placeholder="Adicione um comentário..."
                    rows={2}
                    style={{ borderRadius: 8, border: `1.5px solid ${BORDER}`, padding: "10px 12px", fontSize: 14, resize: "vertical" as const, fontFamily: "inherit" }}
                  />
                  <div style={{ display: "flex", justifyContent: "flex-end", marginTop: 8 }}>
                    <button
                      onClick={handleComment}
                      disabled={submitting || !commentText.trim()}
                      style={{ padding: "8px 18px", backgroundColor: commentText.trim() ? GOLD : BORDER, color: commentText.trim() ? "#fff" : MUTED, border: "none", borderRadius: 8, cursor: commentText.trim() ? "pointer" : "default", fontWeight: 700, fontSize: 13 }}
                    >
                      {submitting ? "Enviando..." : "Comentar"}
                    </button>
                  </div>
                </div>
              </div>
            </div>
          )}

          {comments.length === 0 ? (
            <p style={{ color: MUTED, textAlign: "center", padding: "20px 0", fontSize: 14 }}>Seja o primeiro a comentar!</p>
          ) : (
            comments.map(c => (
              <CommentItem
                key={c.id}
                comment={c}
                onReply={handleReply}
                currentUserId={profile?.id}
                mentionMap={mentionMap}
                highlighted={c.id === highlightCommentId}
                highlightRef={c.id === highlightCommentId ? highlightRef : undefined}
              />
            ))
          )}
        </div>
      </div>
    </AppShell>
  );
}
